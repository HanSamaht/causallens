def _bar(val: float, max_abs: float, cls: str) -> str:
    """Return HTML bar element."""
    w = int(abs(val) / max_abs * 120) if max_abs > 0 else 0
    return f'<span class="bar {cls}" style="width:{w}px"></span>'


def generate_html(session, sample_index: int = 0, output_path: str = "mic_report.html",
                  lang: str = "en") -> str:
    """Generate a self-contained HTML interrogation report."""
    drv = session.driver
    pack = session.pack
    L = _EN

    # ---- Attribution ----
    try:
        attr = session.get_attribution(sample_index)
    except Exception:
        if drv.kind in ("torch", "timeseries"):
            x = drv.sample_at(sample_index)
            grad_attr = drv.input_attribution(x)
            ranked = sorted(zip(drv.feature_names, grad_attr), key=lambda t: -abs(t[1]))[:10]
            max_abs = max(abs(v) for _, v in ranked) or 1
            attr = {"attributions": [
                {"feature": f, "concept": pack.concept_of(f.split("@")[0]), "value": float(x[drv.feature_names.index(f)]),
                 "shap": float(v), "share": abs(v) / max_abs, "role": "normal"}
                for f, v in ranked
            ], "prediction": float(drv.predict_one(x)), "semantics": drv.prediction_semantics}
        else:
            raise

    max_shap = max(abs(a["shap"]) for a in attr["attributions"][:10]) or 1
    attr_rows = []
    for a in attr["attributions"][:10]:
        cls = "bar-pos" if a["shap"] > 0 else "bar-neg"
        if a["role"] == "spurious":
            role_tag = f'<span class="tag tag-warn">{L["spurious"]}</span>'
        elif a["role"] == "proxy":
            role_tag = f'<span class="tag tag-warn">{L["proxy"]}</span>'
        else:
            role_tag = ""
        attr_rows.append(
            f'<tr><td style="color:#79c0ff">{a["feature"]}</td>'
            f'<td>{a["concept"]}</td>'
            f'<td>{a["value"]:+.3f}</td>'
            f'<td>{_bar(a["shap"], max_shap, cls)} {a["shap"]:+.4f}</td>'
            f'<td>{a["share"]:.0%}</td><td>{role_tag}</td></tr>'
        )

    # ---- Circuit (torch models only) ----
    circuit_html = ""
    if drv.kind in ("torch", "timeseries"):
        try:
            c = session.discover_circuit(capability_samples=12)
            if "circuit_units" in c:
                units_in = {u["unit"] for u in c["circuit_units"]}
                chips = []
                for u in range(c["n_units_total"]):
                    cls = "unit-in" if u in units_in else "unit-out"
                    chips.append(f'<span class="unit {cls}">u{u}</span>')
                circuit_html = f"""
<h2>🔌 {L['circuit'].format(mode=c['mode'])}</h2>
<div class="card">
  <div class="circuit-viz">{"".join(chips)}</div>
  <div style="margin-top:8px;color:#8b949e;font-size:0.8em">
    {L['circuit_members']}: {c['n_circuit']}/{c['n_units_total']} · {L['prunable']}: {c['n_pruned']}
    · {L['sparsity']} {c['sparsity']:.0%} · {L['residual']} {c['residual_after_restore']:.4f}
  </div>
</div>"""
        except Exception:
            pass

    # ---- SAE (torch models only) ----
    sae_html = ""
    if drv.kind in ("torch", "timeseries"):
        try:
            s = session.sae_features(top_k=6)
            if s.get("features"):
                rows = []
                for f in s["features"]:
                    corr = ", ".join(f"{k}({v:+.2f})" for k, v in f.get("correlates_with", {}).items())
                    vc = "tag-pass" if f["verdict"].startswith(("passed", "Causally")) else "tag-warn"
                    vt = L["sae_pass"] if f["verdict"].startswith(("passed", "Causally")) else L["sae_fail"]
                    rows.append(
                        f'<tr><td>feat{f["feature"]}</td><td>{f["active_frac"]:.0%}</td>'
                        f'<td style="color:#79c0ff">{corr}</td>'
                        f'<td>{f.get("causal_effect", "-")}</td>'
                        f'<td><span class="tag {vc}">{vt}</span></td></tr>'
                    )
                n_base = max(len(getattr(drv, "base_feature_names", drv.feature_names)), 1)
                sae_html = f"""
<h2>🧬 {L['sae'].format(n=s.get('n_features', 0) // n_base)}</h2>
<table>
<tr><th>{L['sae_feature']}</th><th>{L['sae_active']}</th><th>{L['sae_corr']}</th><th>{L['sae_causal']}</th><th>{L['sae_verdict']}</th></tr>
{"".join(rows)}
</table>"""
        except Exception:
            pass

    # ---- Activation Mediation ----
    activation_html = ""
    if drv.kind in ("torch", "timeseries"):
        try:
            ref = (sample_index + 1) % len(drv.background)
            g = session.activation_graph(sample_index, ref)
            layer_rows = []
            for e in g["edges"]:
                if e["kind"] == "layer_mediation":
                    rec = e.get("recovery")
                    rec_str = f"{rec:.2f}" if rec is not None else "-"
                    layer_rows.append(
                        f'<tr><td>{e["source"]}</td><td>{_bar(abs(e["effect"]), 1, "bar-pos")} {e["effect"]:+.4f}</td>'
                        f'<td>{rec_str}</td></tr>'
                    )
            if layer_rows:
                activation_html = f"""
<h2>⚡ {L['activation']}</h2>
<table><tr><th>{L['layer_col']}</th><th>{L['effect_col']}</th><th>{L['recovery_col']}</th></tr>{"".join(layer_rows)}</table>"""
        except Exception:
            pass

    # ---- Faithfulness ----
    faith = session.run_faithfulness(sample_index)
    fc = "tag-pass" if faith["passed"] else "tag-fail"
    ft = L["faith_pass"] if faith["passed"] else L["faith_fail"]
    faith_html = (
        f'<span class="tag {fc}">{ft}</span> '
        f'{L["comprehensiveness"]} delta={faith["comprehensiveness"]:.3f} | '
        f'{L["random_baseline"]} delta={faith["random_baseline"]:.3f} | '
        f'{L["sufficiency"]} delta={faith["sufficiency"]:.3f} ({L["top_k"]}={faith["top_k"]})'
    )

    html = _TEMPLATE.format(
        lang=lang,
        model_name=drv.name,
        domain=pack.domain,
        driver_kind=drv.kind,
        timestamp=datetime.now().strftime("%Y-%m-%d %H:%M"),
        n_features=len(drv.feature_names),
        n_classes=getattr(drv, "n_classes", 2),
        n_samples=len(drv.background),
        _title=L["title"],
        _model=L["model"], _domain=L["domain"], _driver=L["driver"],
        _features=L["features"], _classes=L["classes"], _samples=L["samples"],
        _attribution_header=L["attribution"].format(n=10),
        _feature_col=L["feature_col"], _concept_col=L["concept_col"],
        _value_col=L["value_col"], _shap_col=L["shap_col"],
        _share_col=L["share_col"], _role_col=L["role_col"],
        attr_rows="".join(attr_rows),
        circuit_html=circuit_html,
        sae_html=sae_html,
        activation_html=activation_html,
        _faith=L["faith"],
        faith_html=faith_html,
        _footer=L["footer"], _footer_tag=L["footer_tag"],
    )
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html)
    return output_path
